// builds pcab75d.js from pcab73.js: game setTimeout callbacks run on the virtual (pumped) clock, not real time,
// so v7.4 timers (radio chatter, voice replies) no longer race with screenshots. Harness sleeps keep the real timer.
const fs = require('fs');
let s = fs.readFileSync(__dirname + '/pcab73.js', 'utf8');
const A = 'const INJECT = `(() => {';
if (!s.includes(A)) throw new Error('inject anchor');
s = s.replace(A, A + `
  const RST = window.setTimeout.bind(window), RCT = window.clearTimeout.bind(window); window.__realST = RST;
  const VT = []; let vid = 1e6;
  window.setTimeout = (fn, ms, ...a) => { if (typeof fn !== 'function') return RST(fn, ms); const id = ++vid; VT.push({ id, due: (window.__vnow || 0) + (+ms || 0), fn, a }); return id; };
  window.clearTimeout = id => { const i = VT.findIndex(t => t.id === id); if (i >= 0) VT.splice(i, 1); else RCT(id); };
  window.__vtick = n => { window.__vnow = n; VT.sort((x, y) => x.due - y.due || x.id - y.id); while (VT.length && VT[0].due <= n){ const t = VT.shift(); try { t.fn(...t.a); } catch (e) { console.error('vt', e && e.message); } } };`);
const B = 'const flush = () => { pend = false; const L = q.splice(0); now += 1000 / 60;';
if (!s.includes(B)) throw new Error('flush anchor');
s = s.replace(B, B + ' window.__vtick(now);');
s = s.replace("pend = true; setTimeout(flush, 16);", "pend = true; window.__realST(flush, 16);");
s = s.replace('const sleep = ms => new Promise(r => setTimeout(r, ms));', 'const sleep = ms => new Promise(r => window.__realST(r, ms));');
s = s.replace("const OUT = 'D:/AI/pm_v6/shots/pcab/';", "const OUT = 'D:/AI/pm_v6/shots/pcab75d/';");
s = s.replace('// node pcab67.js', '// (generated by mk_pcab75d.js) node pcab75d.js');
fs.writeFileSync(__dirname + '/pcab75d.js', s);
let d = fs.readFileSync(__dirname + '/diff73.js', 'utf8');
d = d.split('/shots/pcab/').join('/shots/pcab75d/').split('D:/AI/pm_v6/shots/pcab/').join('D:/AI/pm_v6/shots/pcab75d/');
d = d.split('127.0.0.1:8798/tests/').join('127.0.0.1:8834/tests/');   // own http server (8798 belongs to the v7.4 helper)
fs.writeFileSync(__dirname + '/diff75d.js', d);
console.log('ok', s.length, d.length);
