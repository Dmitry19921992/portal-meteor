// v8.18: voice-pack subtitles for languages without an own voice pack -> v818_subs.js
// source: D:\AI\pm_l10n\voice_lines_<code>.json (id = type.kind.i, as in assets/voice66.json / voice68_*.json)
const fs = require('fs'), path = require('path');
const W = 'D:/AI/pm_l10n/', OUT = path.join(__dirname, '..', 'v818_subs.js');
const ru = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'assets', 'voice66.json'), 'utf8'));
const en = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'assets', 'voice68_en.json'), 'utf8'));
// check alignment with the EN pack (the silent languages play the EN pack indices)
const ven = JSON.parse(fs.readFileSync(W + 'voice_lines_en.json', 'utf8'));
let ok = 0, bad = 0;
for (const l of ven.lines){ const [t, k, i] = l.id.split('.'); const it = en[t] && en[t][k] && en[t][k][+i]; if (it && it.t === l.en) ok++; else { bad++; if (bad < 6) console.log('EN mismatch', l.id, JSON.stringify(l.en), '|', it && it.t); } }
console.log('EN alignment ok', ok, 'bad', bad);
let rk = 0, rb = 0;
for (const l of ven.lines){ const [t, k, i] = l.id.split('.'); const it = ru[t] && ru[t][k] && ru[t][k][+i]; if (it && it.t === l.ru) rk++; else rb++; }
console.log('RU alignment ok', rk, 'bad', rb);
const out = {}, stat = {};
for (const f of fs.readdirSync(W).filter(f => /^voice_lines_[a-zA-Z-]+\.json$/.test(f))){
  const c = f.slice(12, -5); if (c === 'ru' || c === 'en') continue;
  const J = JSON.parse(fs.readFileSync(W + f, 'utf8')); const m = {};
  for (const l of J.lines || []) if (l.text && typeof l.text === 'string') m[l.id] = l.text;
  out[c] = m; stat[c] = Object.keys(m).length;
}
console.log(JSON.stringify(stat));
const head = '// v8.18: subtitles of the unit / curator voice lines for languages WITHOUT their own voice pack (the voice stays silent, text is shown).\n' +
  '// key = type.kind.i of the EN pack (assets/voice68_en.json); generated by tests818/mksubs.js from D:/AI/pm_l10n/voice_lines_<code>.json\n' +
  '// (Claude API 07.11.2026, machine translation, not reviewed by native speakers).\n';
fs.writeFileSync(OUT, head + 'const SUB818 = ' + JSON.stringify(out) + ';\n');
console.log('wrote', OUT, fs.statSync(OUT).size);
